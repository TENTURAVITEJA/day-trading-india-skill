"""Price alerts and NSE clock for trader-alerts. Standard library only.

    python3 alerts.py clock                          # is NSE open? next open / close
    python3 alerts.py quote ADANIENT --write             # quotes -> trader/prices.json
    python3 alerts.py quote --holdings --write       # every ticker in your portfolio and plan
    python3 alerts.py add --from-plan                # stop, target and flat-by-close from trader/plan.json
    python3 alerts.py add --symbol ADANIENT --stop 2737.75
    python3 alerts.py add --symbol ADANIENT --target 2830.00
    python3 alerts.py add --at 15:15 --label "flat by close" --before-close
    python3 alerts.py add --symbol TCS --pct 3
    python3 alerts.py add --opening-bell
    python3 alerts.py check                          # rings what hit, once; exit 1 if nothing rang
    python3 alerts.py check --now "2026-11-11 15:15" --offline tests/fixtures/trader-alerts
    python3 alerts.py list
    python3 alerts.py reset adanient-plan-stop

Rule types:
  above / target  the price is at or above "price"
  below / stop    the price is at or below "price"
  pct_move        the price moved "pct" percent or more from the previous close
                  (or from "ref" if you give one); "direction": "up" or "down"
  opening_bell    NSE opened today (rings once per trading day)
  time            the IST clock passed "at" (HH:MM) on a trading day
                  (rings once per trading day); "before_close": true moves it
                  3 hours earlier on a 1:00 p.m. early close, so a 15:15
                  "flat by close" rings at 12:55 on those days

A rule with "date" is only watched on that IST date (rules from a plan
are for the plan's day only). An above / below alert rings ONCE and then stays
quiet until you reset it, unless the rule has "rearm": true (it re-arms when
the price crosses back). A pct_move alert rings at most once per day.

Quotes: Zerodha Kite Connect /quote (live last traded price, day high / low,
previous close), every ticker in one request, through trader-broker/kite.py
(log in once a day:  kite.py login).
  --offline DIR reads DIR/kite-<TICKER>.json (or .json.gz) instead: one Kite
  quote object ({"last_price", "ohlc": {...}, "last_trade_time"}).

NSE calendar: the 2026 trading holidays as
published by NSE (equity segment trading holidays circular for 2026).
Outside those years the clock says the holiday list is unknown.
"""

